class TestImageNormalizeCallerSafety:
    """Pins the ``image.sub(mean).div_(std)`` idiom used by ``CUTIE.encode_image``/
    ``encode_mask`` (cutie/model/cutie.py): the caller's frame tensor must never be
    mutated, even though the ``std`` division happens in place on a fresh copy.
    """

    def test_normalize_matches_out_of_place_reference_and_leaves_caller_tensor_untouched(self) -> None:
        """sub().div_() matches (image - mean) / std and does not mutate the input tensor."""
        image = torch.randn(1, 3, 8, 8)
        image_snapshot = image.clone()
        mean = torch.tensor([0.485, 0.456, 0.406]).view(-1, 1, 1)
        std = torch.tensor([0.229, 0.224, 0.225]).view(-1, 1, 1)

        expected = (image - mean) / std
        normalized = image.sub(mean).div_(std)

        torch.testing.assert_close(normalized, expected)
        torch.testing.assert_close(image, image_snapshot)
